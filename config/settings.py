# Helper function to strip out separate entries from a .env list
# We assume the separator is a comma
def env_list(name, default=''):
    return [v.strip() for v in os.environ.get(name, default).split(',') if v.strip()]

# Helper function to read a secret from the file named by <name>_FILE, which is
# how Docker secrets arrive, falling back to the plain environment variable
def env_secret(name):
    path = os.environ.get(f'{name}_FILE')
    if path:
        return Path(path).read_text().strip()
    return os.environ.get(name)


